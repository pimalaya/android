package org.pimalaya.client;

import java.util.Map;
import org.json.JSONObject;

/**
 * One OAuth 2.0 authorization code grant with PKCE: holds the CSRF
 * state and PKCE verifier the bridge generated, builds the
 * authorization URL to open in the user's browser, and exchanges the
 * redirect for tokens. Keep the instance alive between
 * {@link #authorizeUrl} and {@link #redeem} so the state and verifier
 * match. {@link #redeem} blocks, so callers must run it off the main
 * thread.
 */
public final class OauthSession {
    private final String clientId;
    private final String clientSecret;
    private final String redirectUri;
    private final String scope;
    private final String state;
    private final String pkceVerifier;

    /**
     * Prepares a grant for the app's OAuth client, its state and
     * verifier freshly generated by the bridge. The redirect URI is
     * the app link, custom scheme or loopback URL the app intercepts;
     * the scope usually comes from the matching
     * {@link AuthMethod#scope}. The client secret is null unless the
     * registration issued one (Google desktop-type clients require it
     * in the exchange).
     */
    public static OauthSession start(OauthRequest request) {
        JSONObject params = Replies.object(Native.oauthSessionParams());
        return new OauthSession(
                request, Json.string(params, "state"), Json.string(params, "verifier"));
    }

    /**
     * Rebuilds a grant from persisted state and PKCE verifier, so the
     * redirect can still be redeemed when the process died while the
     * user was in the browser (the scope only matters before the
     * authorization request, so it may be empty here).
     */
    public static OauthSession resume(OauthRequest request, String state, String pkceVerifier) {
        return new OauthSession(request, state, pkceVerifier);
    }

    private OauthSession(OauthRequest request, String state, String pkceVerifier) {
        this.clientId = request.clientId();
        this.clientSecret = request.clientSecret() == null ? "" : request.clientSecret();
        this.redirectUri = request.redirectUri();
        this.scope = request.scope() == null ? "" : request.scope();
        this.state = state;
        this.pkceVerifier = pkceVerifier;
    }

    /** The scopes the authorization request asks for; empty when unknown. */
    public String scope() {
        return scope;
    }

    /** The CSRF state of the authorization request, for persistence. */
    public String state() {
        return state;
    }

    /** The PKCE verifier of the authorization request, for persistence. */
    public String pkceVerifier() {
        return pkceVerifier;
    }

    /**
     * Builds the authorization URL to open in the user's browser.
     * {@code extras} carries provider-specific query parameters
     * (nullable), e.g. Google's {@code access_type=offline} and
     * {@code prompt=consent} without which no refresh token is issued.
     */
    public String authorizeUrl(String authorizationEndpoint, Map<String, String> extras) {
        JSONObject reply =
                Replies.object(
                        Native.oauthAuthorizeUrl(
                                authorizationEndpoint,
                                clientId,
                                redirectUri,
                                scope,
                                state,
                                pkceVerifier,
                                extras == null ? "" : new JSONObject(extras).toString()));
        return Json.string(reply, "url");
    }

    /**
     * Validates the intercepted redirect URL (CSRF state check) and
     * exchanges its authorization code for tokens.
     */
    public OauthTokens redeem(String tokenEndpoint, String redirectUrl) {
        return redeem(tokenEndpoint, redirectUrl, null);
    }

    /**
     * {@link #redeem(String, String)}, the redirect also refused when its
     * RFC 9207 {@code iss} names another server than {@code issuer}, the
     * one the grant started at (null when unknown): that is the mix-up
     * attack, a server bouncing the browser to another so that the code
     * lands at its own token endpoint.
     */
    public OauthTokens redeem(String tokenEndpoint, String redirectUrl, String issuer) {
        JSONObject validated =
                Replies.object(
                        Native.oauthValidateRedirect(
                                redirectUrl, state, issuer == null ? "" : issuer));
        String code = Json.string(validated, "code");

        Transport transport = new Transport();
        try {
            JSONObject reply =
                    Replies.object(
                            Native.oauthRequestAccessToken(
                                    transport,
                                    tokenEndpoint,
                                    clientId,
                                    clientSecret,
                                    code,
                                    redirectUri,
                                    pkceVerifier));
            return OauthTokens.from(reply);
        } finally {
            transport.close();
        }
    }
}
